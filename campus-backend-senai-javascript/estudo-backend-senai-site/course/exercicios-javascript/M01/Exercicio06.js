// Objetivo: entender que let permite reatribuir o valor da variável.

let estoque = 50;

estoque += 20; // estoque = estoque + 20
console.log(estoque);

estoque -= 10; // estoque = estoque - 10
console.log(estoque);

estoque *= 2;  // estoque = estoque * 2
console.log(estoque);

estoque /= 2;  // estoque = estoque / 2
console.log(estoque);

package modulo04_lacos_repeticao_for;

// Exercício 02
// Objetivo: Utilizar o laço FOR para exibir os números de 5 até 15.
//
// Estrutura do FOR:
// 1. Inicialização -> O contador começa em 5.
// 2. Condição -> O laço continua enquanto o contador for menor ou igual a 15.
// 3. Incremento -> O contador é aumentado em 1 a cada repetição.

public class Exercicio02 {

    public static void main(String[] args) {

        // Percorre os números de 5 até 15
        for (int contador = 5; contador <= 15; contador++) {

            // Exibe o valor atual do contador
            System.out.println(contador);
        }
    }
}

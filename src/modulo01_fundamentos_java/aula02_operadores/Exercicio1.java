package modulo01_fundamentos_java.aula02_operadores;

/*
 * ============================================================
 * Curso Java
 * Módulo 01 - Fundamentos Java
 * Aula 02 - Operadores
 * Exercício 01
 * ============================================================
 *
 * Objetivo:
 * Praticar os operadores aritméticos realizando operações
 * de soma, subtração, multiplicação, divisão e cálculo do
 * resto da divisão entre dois números inteiros.
 */

public class Exercicio1 {
    public static void main(String[] args) {
        int numero1 = 20;
        int numero2 = 8;

        System.out.println(numero1 + numero2);
        System.out.println(numero1 - numero2);
        System.out.println(numero1 * numero2);
        System.out.println(numero1 / numero2);
        System.out.println(numero1 % numero2);
    }
}
